GUARDRAIL_REFUSAL = (
    "Я не даю персональных инвестиционных рекомендаций и не работаю "
    "с реальными платёжными данными. Но могу помочь разобраться "
    "в твоих доходах, расходах и бюджете — спроси об этом."
)


def check_guardrails(user_message: str) -> Optional[str]:
    """Возвращает готовый отказ, если сообщение попадает в запрещённую тему.
    None — если сообщение можно передавать в LLM."""
    text = user_message.lower()
    for pattern in FORBIDDEN_PATTERNS:
        if re.search(pattern, text):
            return GUARDRAIL_REFUSAL
    return None
